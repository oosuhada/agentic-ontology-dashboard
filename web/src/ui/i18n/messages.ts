export const MESSAGE_CATALOG: Record<AppLocale, Record<MessageKey, string>> = {
  "ko-KR": koKR,
  "en-US": enUS,
};

export function translate(locale: AppLocale, key: MessageKey, values?: Record<string, string | number>) {
  const template = MESSAGE_CATALOG[locale][key] ?? MESSAGE_CATALOG["en-US"][key] ?? key;
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [name, replacement]) => result.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}
