"""Persistence port for Dataset catalog, provenance, and projection state."""

from __future__ import annotations

from typing import Any, Protocol


class DatasetRepositoryPort(Protocol):
    def create_dataset(self, **kwargs: Any) -> dict[str, Any]: ...

    def list_datasets(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def list_dataset_page(self, **kwargs: Any) -> dict[str, Any]: ...

    def get_dataset(self, **kwargs: Any) -> dict[str, Any]: ...

    def create_version(self, **kwargs: Any) -> dict[str, Any]: ...

    def list_versions(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def get_version(self, **kwargs: Any) -> dict[str, Any]: ...

    def list_files(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def list_ingestion_runs(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def list_quarantine_records(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def latest_materialization(self, **kwargs: Any) -> dict[str, Any]: ...

    def save_mapping(self, **kwargs: Any) -> dict[str, Any]: ...

    def get_mapping(self, **kwargs: Any) -> dict[str, Any]: ...

    def list_mappings(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def list_projections(self, **kwargs: Any) -> list[dict[str, Any]]: ...

    def claim_projection(self, **kwargs: Any) -> dict[str, Any]: ...

    def complete_projection(self, **kwargs: Any) -> None: ...

    def fail_projection(self, **kwargs: Any) -> None: ...

    def retry_projection(self, **kwargs: Any) -> dict[str, Any]: ...

    def create_materialization(self, **kwargs: Any) -> dict[str, Any]: ...

    def list_materializations(self, **kwargs: Any) -> list[dict[str, Any]]: ...


__all__ = ["DatasetRepositoryPort"]
